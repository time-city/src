// Get translation helper - supports nested keys
export function t(key, lang) {
  const currentLang = lang || (typeof window !== 'undefined' ? localStorage.getItem('lang') || 'vi' : 'vi');
  const keys = key.split('.');
  let value = translations[currentLang];
  
  for (const k of keys) {
    value = value?.[k];
    if (value === undefined) break;
  }
  
  // Fallback to Vietnamese if not found
  if (value === undefined && currentLang !== 'vi') {
    value = translations.vi;
    for (const k of keys) {
      value = value?.[k];
      if (value === undefined) break;
    }
  }
  
  return value !== undefined ? value : key;
}
